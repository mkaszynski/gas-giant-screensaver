#!/usr/bin/env python3
"""Integrate the prescribed three-wave crest distribution offline.

The renderer interpolates this small inverse-CDF table once per weather state;
it never performs phase quadrature while drawing. No photographs or noise maps.
"""

import argparse
from pathlib import Path
import numpy as np

WEIGHTS = np.array([0.58, 0.27, 0.15])
MIN_COVERAGE, MAX_COVERAGE, COUNT = 1e-7, 0.12, 64


def crest_quantiles():
    nodes, weights = np.polynomial.legendre.leggauss(256)
    cosines = np.cos((nodes + 1) * np.pi * 0.5)
    score = WEIGHTS[0] * cosines[:, None] + WEIGHTS[1] * cosines[None, :]
    probability = weights[:, None] * weights[None, :] * 0.25
    result = []
    for coverage in np.geomspace(MIN_COVERAGE, MAX_COVERAGE, COUNT):
        low, high = -1.0, 1.0
        for _ in range(36):
            threshold = (low + high) * 0.5
            tail = np.arccos(np.clip((threshold - score) / WEIGHTS[2], -1, 1)) / np.pi
            if np.sum(tail * probability) > coverage:
                low = threshold
            else:
                high = threshold
        result.append((low + high) * 0.5)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "src/ocean_quantiles.hpp",
    )
    args = parser.parse_args()
    values = crest_quantiles()
    rows = [
        ", ".join(f"{v:.9f}f" for v in values[i : i + 4]) for i in range(0, COUNT, 4)
    ]
    args.output.write_text(
        "// Generated by scripts/bake_ocean_quantiles.py; do not edit.\n"
        "#pragma once\n#include <array>\nnamespace observatory {\n"
        f"inline constexpr std::array<float, {COUNT}> oceanCrestQuantiles{{\n  "
        + ",\n  ".join(rows)
        + "\n};\n} // namespace observatory\n"
    )


if __name__ == "__main__":
    main()
